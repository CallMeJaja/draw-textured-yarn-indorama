const I18n = {
  currentLocale: localStorage.getItem("locale") || "id",

  t(key, params) {
    let str = locales[this.currentLocale][key] || key;
    if (params) {
      Object.keys(params).forEach((k) => {
        str = str.replace(`{${k}}`, params[k]);
      });
    }
    return str;
  },

  apply(locale) {
    this.currentLocale = locale;
    localStorage.setItem("locale", locale);
    document.documentElement.lang = locale;

    // Text content
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const str = locales[locale][key];
      if (str !== undefined) {
        el.innerHTML = str;
      }
    });

    // Attributes
    document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      const pairs = el.getAttribute("data-i18n-attr").split(";");
      pairs.forEach((pair) => {
        const [attr, key] = pair.split("|");
        const str = locales[locale][key];
        if (str !== undefined) {
          el.setAttribute(attr, str);
        }
      });
    });

    // Meta tags
    const title = locales[locale]["meta.title"];
    if (title) document.title = title;

    const desc = locales[locale]["meta.description"];
    if (desc) {
      const metaDesc = document.querySelector('meta[name="description"]');
      if (metaDesc) metaDesc.setAttribute("content", desc);
      const ogDesc = document.querySelector('meta[property="og:description"]');
      if (ogDesc) ogDesc.setAttribute("content", desc);
      const twDesc = document.querySelector('meta[name="twitter:description"]');
      if (twDesc) twDesc.setAttribute("content", desc);
    }

    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.setAttribute("content", title);
    const twTitle = document.querySelector('meta[name="twitter:title"]');
    if (twTitle) twTitle.setAttribute("content", title);

    const ogLocale = document.querySelector('meta[property="og:locale"]');
    if (ogLocale)
      ogLocale.setAttribute("content", locales[locale]["meta.og_locale"]);

    // Update dropdown label
    const langLabel = document.getElementById("langCurrent");
    if (langLabel) langLabel.textContent = locale.toUpperCase();
  },

  init() {
    this.apply(this.currentLocale);

    const toggle = document.getElementById("langToggle");
    const dropdown = document.getElementById("langDropdown");
    if (toggle && dropdown) {
      toggle.addEventListener("click", (e) => {
        e.stopPropagation();
        dropdown.classList.toggle("open");
      });

      dropdown.querySelectorAll("[data-locale]").forEach((item) => {
        item.addEventListener("click", () => {
          const locale = item.getAttribute("data-locale");
          this.apply(locale);
          dropdown.classList.remove("open");
        });
      });

      document.addEventListener("click", () => {
        dropdown.classList.remove("open");
      });
    }
  },
};

document.addEventListener("DOMContentLoaded", () => {
  I18n.init();
});
